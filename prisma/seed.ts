async function main() {
  const adminHash = await bcrypt.hash('admin123', 10);
  const editorHash = await bcrypt.hash('editor123', 10);
  const userHash = await bcrypt.hash('user12345', 10);

  const admin = await db.user.upsert({
    where: { email: 'admin@wikinova.local' },
    update: {},
    create: { email: 'admin@wikinova.local', name: 'Администратор', passwordHash: adminHash, role: 'ADMIN' },
  });
  const editor = await db.user.upsert({
    where: { email: 'editor@wikinova.local' },
    update: {},
    create: { email: 'editor@wikinova.local', name: 'Редактор', passwordHash: editorHash, role: 'EDITOR' },
  });
  await db.user.upsert({
    where: { email: 'anna@wikinova.local' },
    update: {},
    create: { email: 'anna@wikinova.local', name: 'Анна К.', passwordHash: userHash, role: 'USER' },
  });
  await db.user.upsert({
    where: { email: 'igor@wikinova.local' },
    update: {},
    create: { email: 'igor@wikinova.local', name: 'Игорь П.', passwordHash: userHash, role: 'USER' },
  });

  for (const c of categories) {
    await db.category.upsert({ where: { slug: c.slug }, update: c, create: c });
  }

  const tagMap = new Map<string, string>();
  for (const t of tags) {
    const slug = slugify(t);
    const row = await db.tag.upsert({
      where: { slug },
      update: {},
      create: { slug, name: t },
    });
    tagMap.set(t, row.id);
  }

  const catRows = await db.category.findMany();
  const catBySlug = new Map(catRows.map((c) => [c.slug, c.id]));

  let i = 0;
  for (const a of articles) {
    i += 1;
    const plain = a.content.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
    const publishedAt = new Date(Date.now() - i * 86400000 * 2);
    const existing = await db.article.findUnique({ where: { slug: a.slug } });
    const data = {
      title: a.title,
      slug: a.slug,
      excerpt: a.excerpt,
      content: a.content,
      coverImage: a.cover,
      status: 'published' as const,
      views: a.views,
      readingTime: Math.max(1, Math.round(plain.split(' ').length / 200)),
      featured: a.featured,
      authorId: i % 3 === 0 ? editor.id : admin.id,
      categoryId: catBySlug.get(a.category) ?? null,
      publishedAt,
      seoTitle: a.title,
      seoDescription: a.excerpt,
    };
    const article = existing
      ? await db.article.update({ where: { id: existing.id }, data })
      : await db.article.create({ data });
    for (const t of a.tags) {
      const tagId = tagMap.get(t);
      if (tagId) {
        await db.articleTag.upsert({
          where: { articleId_tagId: { articleId: article.id, tagId } },
          update: {},
          create: { articleId: article.id, tagId },
        });
      }
    }
  }

  for (const r of requests) {
    const exists = await db.articleRequest.findFirst({ where: { topic: r.topic } });
    if (!exists) {
      await db.articleRequest.create({
        data: { ...r },
      });
    }
  }

  for (const p of defaultPrompts) {
    const exists = await db.aIPrompt.findFirst({ where: { key: p.key, isActive: true } });
    if (!exists) {
      await db.aIPrompt.create({ data: { key: p.key, template: p.template, version: 1, isActive: true } });
    }
  }

  const blocks = Object.entries(BLOCK_DEFAULTS);
  for (const [key, value] of blocks) {
    const exists = await db.siteBlock.findUnique({ where: { key } });
    if (!exists) {
      await db.siteBlock.create({ data: { key, value } });
    }
  }

  const aiEnv = {
    baseUrl: process.env.AI_BASE_URL || 'http://localhost:1234/v1',
    model: process.env.AI_MODEL || 'google/gemma-4-12b-qat',
    temperature: Number(process.env.AI_TEMPERATURE || 0.7),
    maxTokens: Number(process.env.AI_MAX_TOKENS || 6144),
    timeoutMs: Number(process.env.AI_TIMEOUT_MS || 60000),
    apiKeyEncrypted: process.env.AI_API_KEY ? encryptSecret(process.env.AI_API_KEY) : '',
  };
  const settingsCount = await db.aISettings.count();
  if (settingsCount === 0) {
    await db.aISettings.create({ data: aiEnv });
  }

  await db.activityLog.createMany({
    data: [
      { userId: admin.id, action: 'seed', entity: 'system', entityId: null },
      { userId: editor.id, action: 'login', entity: 'user', entityId: editor.id },
    ],
  });

  console.log('Seed done. Admin: admin@wikinova.local / admin123, Editor: editor@wikinova.local / editor123');
  console.log('Masked AI key:', maskKey(process.env.AI_API_KEY || ''));
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => db.$disconnect());
